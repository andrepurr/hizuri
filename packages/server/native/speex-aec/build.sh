#!/bin/sh
# Builds speex-aec.wasm from speexdsp (BSD, COPYING-speexdsp) and aec.c, then embeds it as base64 in
# packages/server/src/server/session/voice/speex-aec-wasm.ts. Needs only zig (pip install ziglang)
# and a speexdsp checkout: build.sh <speexdsp-dir> <zig>. Built from speexdsp 7a15878.
set -e
S=$1/libspeexdsp; Z=${2:-zig}; HERE=$(dirname "$0")
cat > "$1/include/speex/speexdsp_config_types.h" <<H
#include <stdint.h>
typedef int16_t spx_int16_t; typedef uint16_t spx_uint16_t;
typedef int32_t spx_int32_t; typedef uint32_t spx_uint32_t;
H
"$Z" cc -target wasm32-wasi -O2 -s -DFLOATING_POINT -DUSE_SMALLFT -DEXPORT= -I"$1/include" -I"$S" \
  -mexec-model=reactor "$S/mdf.c" "$S/preprocess.c" "$S/fftwrap.c" "$S/smallft.c" "$S/filterbank.c" \
  "$HERE/aec.c" -o "$HERE/speex-aec.wasm"
{
  echo "// Generated by packages/server/native/speex-aec/build.sh: speexdsp's echo canceller as WASM."
  echo "// speexdsp is BSD-licensed (packages/server/native/speex-aec/COPYING-speexdsp)."
  printf 'export const SPEEX_AEC_WASM_BASE64 =\n  "%s";\n' "$(base64 -w0 "$HERE/speex-aec.wasm")"
} > "$HERE/../../src/server/session/voice/speex-aec-wasm.ts"
rm "$HERE/speex-aec.wasm"
